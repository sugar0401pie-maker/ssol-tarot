export function threeJsonLd(site: string) {
  const url = `${site}${THREE_PATH}`;
  return {
    "@context": "https://schema.org",
    "@graph": [
      { "@type": "WebPage", "@id": `${url}#page`, url, name: THREE_TITLE, description: THREE_DESC, inLanguage: "ko-KR" },
      { "@type": "FAQPage", mainEntity: FAQ.map((f) => ({ "@type": "Question", name: f.q, acceptedAnswer: { "@type": "Answer", text: f.a } })) },
      {
        "@type": "BreadcrumbList",
        itemListElement: [
          { "@type": "ListItem", position: 1, name: "쏠 타로 하우스", item: `${site}/` },
          { "@type": "ListItem", position: 2, name: "타로 3장 배열 보는 법", item: url },
        ],
      },
    ],
  };
}
