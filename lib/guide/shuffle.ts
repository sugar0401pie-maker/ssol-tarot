export function shuffleTexts(): string[] {
  return [SHUFFLE_TITLE, SHUFFLE_H1, SHUFFLE_DESC, ...SECTIONS.flatMap((s) => [s.h, ...s.p, ...(s.list ?? [])]), ...FAQ.flatMap((f) => [f.q, f.a])];
}

export function shuffleJsonLd(site: string) {
  const url = `${site}${SHUFFLE_PATH}`;
  return {
    "@context": "https://schema.org",
    "@graph": [
      { "@type": "WebPage", "@id": `${url}#page`, url, name: SHUFFLE_TITLE, description: SHUFFLE_DESC, inLanguage: "ko-KR" },
      { "@type": "FAQPage", mainEntity: FAQ.map((f) => ({ "@type": "Question", name: f.q, acceptedAnswer: { "@type": "Answer", text: f.a } })) },
      {
        "@type": "BreadcrumbList",
        itemListElement: [
          { "@type": "ListItem", position: 1, name: "쏠 타로 하우스", item: `${site}/` },
          { "@type": "ListItem", position: 2, name: "타로 셔플하는 법", item: url },
        ],
      },
    ],
  };
}
