/** 주소(예: "/", "/cards/the-fool")의 문구에 지금 가격을 넣어 돌려준다. 표에 없는 주소면 null. */
export function pageMeta(path: string, now: Date = new Date()): PageMeta | null {
  const m = PAGE_META[path];
  if (!m) return null;
  const price = won(currentReportPrice(now));
  const fill = (s: string) => s.replaceAll("{price}", price);
  return { title: fill(m.title), description: fill(m.description), ogTitle: fill(m.ogTitle), ogDescription: fill(m.ogDescription) };
}

